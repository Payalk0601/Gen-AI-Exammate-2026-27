def hit(title, text, score=0.6, page=3, cid="x"):
    return {"chunk_id": cid, "score": score, "text": text, "title": title, "source": "rules.pdf", "page": page}


BURN = hit("Rule 5: Duties of waste generator", "No waste generator shall throw, burn or bury the solid waste generated by him on streets, open public spaces or in drains.", 0.52, cid="a")
SEG = hit("Rule 5: Duties of waste generator", "Every waste generator shall segregate waste at source into separate streams: wet, dry, sanitary and special care waste, and hand it over to authorised waste pickers.", 0.64, cid="b")
BINS = hit("Rule 39: Duties of local bodies", "Local bodies shall paint public bins green for wet waste and blue for dry waste. Red bins may be placed in public toilets.", 0.40, page=30, cid="c")


class GateTests(unittest.TestCase):
    def test_amount_question_without_amount_is_refused(self):
        ans = rag.answer_question("What is the exact fine in rupees for a household that burns waste?",
                                  lambda q, k: [BURN, SEG], generator=rag.ExtractiveGenerator())
        self.assertFalse(ans.answered)
        self.assertEqual(ans.reason, "no_amount_in_sources")
        self.assertEqual(ans.answer, rag.IDK)
        self.assertEqual(ans.citations, [])
        self.assertTrue(ans.considered)                    # what was looked at is still reported

    def test_amount_question_with_amount_in_source_is_not_blocked(self):
        paid = hit("Rule 9: Fees", "The user fee shall be Rs. 50 per month for every household as the local body decides.", 0.7)
        self.assertIsNone(rag.evidence_gate("How much is the user fee?", rag._sources([paid]), 0.3))

    def test_low_similarity_is_refused(self):
        weak = hit("Rule 5: Duties", "Every waste generator shall segregate waste.", 0.12)
        ans = rag.answer_question("What are the duties of waste generators?", lambda q, k: [weak], generator=rag.ExtractiveGenerator())
        self.assertEqual(ans.reason, "low_similarity")

    def test_off_topic_question_is_refused(self):
        ans = rag.answer_question("Can I get a refund on my income tax?", lambda q, k: [SEG, BINS], generator=rag.ExtractiveGenerator())
        self.assertFalse(ans.answered)
        self.assertEqual(ans.reason, "low_coverage")

    def test_no_sources(self):
        ans = rag.answer_question("Who segregates waste?", lambda q, k: [], generator=rag.ExtractiveGenerator())
        self.assertEqual(ans.reason, "no_sources")


class ExtractiveTests(unittest.TestCase):
    def test_answer_is_a_source_sentence_with_citation(self):
        ans = rag.answer_question("What bin colours must my municipality use?", lambda q, k: [BINS], generator=rag.ExtractiveGenerator())
        self.assertTrue(ans.answered)
        self.assertIn("green for wet waste", ans.answer)
        self.assertIn("[1]", ans.answer)
        self.assertEqual(ans.citations[0].title, "Rule 39: Duties of local bodies")
        self.assertEqual(ans.citations[0].page, 30)
        self.assertEqual(ans.citations[0].source, "rules.pdf")

    def test_citations_are_renumbered_from_one(self):
        ans = rag.answer_question("Who has to separate waste into which streams?", lambda q, k: [BINS, SEG], generator=rag.ExtractiveGenerator())
        self.assertTrue(ans.answered)
        self.assertEqual([c.n for c in ans.citations], list(range(1, len(ans.citations) + 1)))


class LLMGeneratorTests(unittest.TestCase):
    def setUp(self):
        patcher = mock.patch.dict(os.environ, {"GROQ_API_KEY": "test", "LLM_PROVIDER": "groq"})
        patcher.start()
        self.addCleanup(patcher.stop)
        self.gen = rag.LLMGenerator()

    def ask(self, reply):
        with mock.patch.object(llm, "complete", return_value=reply):
            return rag.answer_question("Who has to separate waste into which streams?", lambda q, k: [SEG, BINS], generator=self.gen)

    def test_cited_reply_is_accepted(self):
        ans = self.ask("Every generator separates waste into four streams [1].")
        self.assertTrue(ans.answered)
        self.assertEqual([c.n for c in ans.citations], [1])

    def test_model_saying_idk_is_a_refusal(self):
        ans = self.ask("I don't know.")
        self.assertFalse(ans.answered)
        self.assertEqual(ans.reason, "model_said_unknown")

    def test_reply_without_citation_is_a_refusal(self):
        ans = self.ask("They separate waste into four streams.")
        self.assertFalse(ans.answered)
        self.assertEqual(ans.reason, "no_citation")

    def test_invented_citation_number_is_ignored(self):
        ans = self.ask("Four streams [9].")
        self.assertEqual(ans.reason, "no_citation")

    def test_llm_failure_falls_back_to_extractive(self):
        with mock.patch.object(llm, "complete", side_effect=llm.LLMError("groq timed out")):
            ans = rag.answer_question("Who has to separate waste into which streams?", lambda q, k: [SEG], generator=self.gen)
        self.assertTrue(ans.answered)
        self.assertIn("fallback", ans.generator)


class LLMWrapperTests(unittest.TestCase):
    def test_env_file_is_read_without_overriding(self):
        path = Path(tempfile.mkdtemp()) / ".env"
        path.write_text('# comment\nKC_TEST_A="one"\nKC_TEST_B=two\n', encoding="utf-8")
        with mock.patch.dict(os.environ, {"KC_TEST_B": "kept"}):
            llm.load_env(path)
            self.assertEqual(os.environ["KC_TEST_A"], "one")
            self.assertEqual(os.environ["KC_TEST_B"], "kept")
        os.environ.pop("KC_TEST_A", None)

    def test_no_key_gives_clear_error(self):
        with mock.patch.dict(os.environ, {"GROQ_API_KEY": "", "GEMINI_API_KEY": ""}), mock.patch.object(llm, "load_env"):
            with self.assertRaises(llm.LLMError):
                llm.complete("s", "u")

    def test_groq_request_shape(self):
        fake = mock.Mock()
        fake.json.return_value = {"choices": [{"message": {"content": " hi "}}]}
        with mock.patch.dict(os.environ, {"GROQ_API_KEY": "secret"}), mock.patch.object(llm.requests, "post", return_value=fake) as post:
            self.assertEqual(llm.complete("sys", "usr", provider="groq"), "hi")
        kwargs = post.call_args.kwargs
        self.assertEqual(kwargs["headers"]["Authorization"], "Bearer secret")
        self.assertEqual(kwargs["json"]["messages"][0]["role"], "system")
        self.assertIn("timeout", kwargs)

    def test_error_message_never_contains_the_key(self):
        import requests
        with mock.patch.dict(os.environ, {"GEMINI_API_KEY": "supersecret"}), \
                mock.patch.object(llm.requests, "post", side_effect=requests.exceptions.ConnectionError("boom supersecret")):
            with self.assertRaises(llm.LLMError) as cm:
                llm.complete("s", "u", provider="gemini")
        self.assertNotIn("supersecret", str(cm.exception))


def load_run_eval():
    spec = importlib.util.spec_from_file_location("run_eval", ROOT / "eval" / "run_eval.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class EvalTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.ev = load_run_eval()

    def test_eval_set_has_15_rows_and_q6_must_refuse(self):
        import json
        rows = json.loads((ROOT / "eval" / "eval_set.json").read_text(encoding="utf-8"))
        self.assertEqual(len(rows), 15)
        self.assertTrue(next(r for r in rows if r["id"] == 6)["must_refuse"])
        self.assertTrue(all("question" in r and "expected_rules" in r for r in rows))

    def test_evaluate_scores_answers_and_refusals(self):
        rows = [{"id": 1, "question": "Who has to separate waste into which streams?", "expected_rules": [5], "must_refuse": False},
                {"id": 2, "question": "What is the exact fine in rupees for a household that burns waste?", "expected_rules": [], "must_refuse": True},
                {"id": 3, "question": "What bin colours must my municipality use?", "expected_rules": [5], "must_refuse": False}]
        results, summary = self.ev.evaluate(rows, lambda q, k: [SEG, BINS], rag.ExtractiveGenerator(), k=2)
        self.assertTrue(results[0]["correct"])
        self.assertTrue(results[1]["correct"])           # refused
        self.assertFalse(results[2]["correct"])          # answered from Rule 39 but Rule 5 was expected
        self.assertEqual(summary["correct"], 2)
        self.assertEqual(summary["refusals_right"], "1/1")
        self.assertEqual(summary["wrong_answers"], 1)

    def test_winner_prefers_accuracy_then_hit_then_smaller_k(self):
        def run(name, acc, hit, k):
            return {"name": name, "k": k, "summary": {"accuracy": acc, "retrieval_hit": hit}}
        a, b, c = run("A", 0.8, 0.9, 5), run("B", 0.8, 0.9, 3), run("C", 0.7, 1.0, 3)
        self.assertIs(self.ev.pick_winner([a, b, c]), b)

    def test_readme_table_is_replaced_between_markers(self):
        path = Path(tempfile.mkdtemp()) / "README.md"
        path.write_text(f"intro\n{self.ev.MARK_START}\nold\n{self.ev.MARK_END}\noutro\n", encoding="utf-8")
        self.ev.update_readme("NEW TABLE", path)
        text = path.read_text(encoding="utf-8")
        self.assertIn("NEW TABLE", text)
        self.assertNotIn("old", text)
        self.assertTrue(text.startswith("intro") and text.rstrip().endswith("outro"))


class AskEndpointTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        try:
            import chromadb  # noqa: F401
        except ImportError:
            raise unittest.SkipTest("chromadb not installed")

    def test_ask_answers_cites_and_refuses(self):
        from fastapi.testclient import TestClient
        import app.main as main
        from app.chunking import Chunk
        from app.embed import HashEmbedder
        from app.vectorstore import VectorStore
        chunks = [Chunk("c1", BINS["text"], "rules.pdf", 30, BINS["title"], "Rules", 0),
                  Chunk("c2", SEG["text"], "rules.pdf", 12, SEG["title"], "Rules", 0)]
        store = VectorStore(path=Path(tempfile.mkdtemp()) / "chroma", embedder=HashEmbedder())
        store.index(chunks)
        client = TestClient(main.app)
        main._STORE = store
        try:
            with mock.patch.dict(os.environ, {"KACHRACHECK_GENERATOR": "extractive"}), mock.patch.object(rag, "MIN_SCORE", 0.0):
                ok = client.post("/ask", json={"question": "What bin colours must municipalities paint public bins?", "k": 2}).json()
                no = client.post("/ask", json={"question": "What is the exact fine in rupees for a household that burns waste?"}).json()
                bad = client.post("/ask", json={"question": "hi"})
            self.assertTrue(ok["answered"])
            self.assertEqual(ok["citations"][0]["page"], 30)
            self.assertFalse(no["answered"])
            self.assertEqual(no["answer"], rag.IDK)
            self.assertEqual(bad.status_code, 422)
        finally:
            main._STORE = None


